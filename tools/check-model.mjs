import assert from 'node:assert/strict';
import { createModel } from '../src/model/model.js';

const model = createModel({ random: () => 0.7 });
model.setArchitecture('count');
model.hear('あ');
model.hear('あ');
model.hear('い');
model.sleep();
const store = structuredClone(model.store);
const probs = () => model.infer('').trace.find(e => e.type === 'probs').candidates;
assert.equal(probs()[0].p, 2 / 3);
assert.equal(model.infer('').text, 'い');
model.setSampler('sampler-temperature', 0.5);
assert.ok(Math.abs(probs()[0].p - 0.8) < 1e-12);
assert.equal(model.infer('').text, 'あ');
model.setSampler('sampler-temperature', 2);
assert.ok(probs()[0].p < 2 / 3 && probs()[0].p > 0.5);
assert.ok(Math.abs(probs().reduce((sum, c) => sum + c.p, 0) - 1) < 1e-12);
assert.deepEqual(model.store, store);
assert.equal(model.setSampler('sampler-temperature', 0), false);
assert.equal(model.setSampler('unknown'), false);
model.tutorial.step = 3;
model.tutorial.reflection = 'slept';
const restored = createModel();
restored.restore(model.snapshot());
assert.equal(restored.chips.sampler.id, 'sampler-temperature');
assert.equal(restored.options.temperature, 2);
assert.equal(restored.tutorial.step, 3);
assert.equal(restored.tutorial.reflection, 'slept');
const legacy = model.snapshot();
delete legacy.options;
delete legacy.tutorial;
legacy.chips.sampler = 'sampler-proportional';
restored.restore(legacy);
assert.equal(restored.chips.sampler.id, 'sampler-proportional');
assert.equal(restored.tutorial.step, 4);
assert.equal(restored.tutorial.reflection, null);
const empty = createModel();
empty.setSampler('sampler-temperature', 0.25);
assert.equal(empty.infer('').text, '……');
console.log('OK 温度ごとの確率・抽選・保存復元・旧セーブ互換・空モデル');
